# Exercício 02 - Operações com dois números

n1 = int(input('Digite o primeiro número:\n'))
n2 = int(input('Digite o segundo número:\n'))

soma = n1 + n2
subtracao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2
divisao2 = n1 // n2
potencia = n1 ** n2
resto = n1 % n2
media = (n1 + n2) / 2

print('A soma dos números é:', soma)
print('A subtração dos números é:', subtracao)
print('A multiplicação dos números é:', multiplicacao)
print('A divisão dos números é:', divisao)
print('A divisão inteira dos números é:', divisao2)
print('A potência dos números é:', potencia)
print('O resto da divisão dos números é:', resto)
print('A média dos números é:', media)